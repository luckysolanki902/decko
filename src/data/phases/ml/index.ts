import { Phase, Topic } from '@/types';

type Project = NonNullable<Topic['project']>;
type TopicSeed = [title: string, items: [string, string, string, string, ...string[]], project?: Project];
type DaySeed = [title: string, topics: [TopicSeed, TopicSeed, TopicSeed, TopicSeed]];

type DeepDaySeed = [
  title: string,
  mentalModel: string,
  mechanics: string,
  buildLab: string,
  evaluation: string,
  project?: Project,
];

function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function deepDay(
  title: string,
  mentalModel: string,
  mechanics: string,
  buildLab: string,
  evaluation: string,
  project?: Project
): DaySeed {
  return [
    title,
    [
      ['Mental Model', [
        mentalModel,
        'Connect this idea to what you already know from data analytics, pandas, or earlier ML lectures',
        'Before reading the explanation, write one prediction, small example, or candidate explanation; use a short guided attempt if the idea is new',
        'Name the real product or research problem this technique was invented to solve',
      ]],
      ['Mechanics & Math', [
        mechanics,
        'Track every shape, dtype, and assumption through the derivation, not just the final equation',
        'Work one tiny numeric example by hand before touching code',
        'Name the assumptions that have to hold for this to be useful and where they break',
      ]],
      ['Build Lab', [
        buildLab,
        'Use only tools already taught: explain an early library call fully, then rebuild its mechanism once prerequisites are ready; offer an executable small-data or CPU route',
        'Add shape, dtype, and range assertions so silent bugs become loud bugs',
        'Compare with a taught reference under matched data, objective, dtype, and justified tolerance; do not demand identical stochastic runs',
      ]],
      ['Evaluation & Failure Modes', [
        evaluation,
        'Inspect individual errors, slices, prompts, or traces — never trust a single average score',
        'Catalogue leakage, overfitting, bias, hallucination, latency, cost, or operational risks for this technique',
        'Write the next experiment from the failure mode you observed',
        'Close the notebook and reconstruct one mechanism; log help used and schedule a delayed changed-task check, initially around 1/3/7/14/30 days',
        'Keep ordinary review within 20 minutes; if weak prerequisites accumulate, pause new material and repair one dependency',
        'Record two competing explanations and the smallest experiment that distinguishes them; distinguish a negative result from an implementation failure',
      ], project],
    ],
  ];
}

function toDays(days: DeepDaySeed[]): DaySeed[] {
  return days.map(([title, m, mech, build, evalp, project]) =>
    deepDay(title, m, mech, build, evalp, project)
  );
}

function capstone(title: string, description: string, features: string[]): Project {
  return { title, description, type: 'capstone', features };
}

function buildPhase(options: {
  id: string;
  number: number;
  title: string;
  subtitle: string;
  goal: string;
  dayStart: number;
  icon: string;
  color: string;
  days: DaySeed[];
  checkpoint: Phase['checkpoint'];
}): Phase {
  const dayEnd = options.dayStart + options.days.length - 1;
  return {
    id: options.id,
    number: options.number,
    title: options.title,
    subtitle: options.subtitle,
    duration: `${options.days.length} Units | ~${options.days.length * 4} baseline hours + review`,
    days: `Days ${options.dayStart}-${dayEnd}`,
    goal: options.goal,
    icon: options.icon,
    color: options.color,
    sections: options.days.map(([dayTitle, topics], index) => {
      const day = options.dayStart + index;
      return {
        id: `day${day}`,
        title: `Day ${day}: ${dayTitle}`,
        duration: '~4h baseline; split across sessions',
        topics: topics.map(([topicTitle, items, project]) => ({
          id: slugify(`${dayTitle}-${topicTitle}`),
          title: topicTitle,
          duration: '1 hour',
          items,
          project,
        })),
      };
    }),
    checkpoint: {
      ...options.checkpoint,
      skills: options.checkpoint?.skills ?? [],
      milestone: `${options.checkpoint?.milestone ?? ''} Gate: explain without notes, build one independent artifact, diagnose a deliberate failure, and repeat a changed task after a delay. Record help and repair missing prerequisites.`,
    },
  };
}

